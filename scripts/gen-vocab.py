#!/usr/bin/env python3
"""Generate the Nordic spelling vocabulary from the Nordic TechDocs Style Guide.

The script reads the term columns of docs/glossary.md and the names in
docs/product-names.md, keeps the words that Vale's default en_US dictionary
does not know, and writes them to config/vocabularies/Nordic/accept.txt.
Prohibited terms are skipped: the ones marked in red in the glossary, and any
word that a Nordic rule such as Nordic.Glossary flags (BLE, NRF52840).

Usage:
    python3 scripts/gen-vocab.py --guide ../techdocs-style-guide
    python3 scripts/gen-vocab.py --guide ../techdocs-style-guide --check

With --check, the script writes nothing and exits with 1 if accept.txt is out
of date. It needs vale on the PATH.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, 'config', 'vocabularies', 'Nordic', 'accept.txt')
HEADER = ('# Generated by scripts/gen-vocab.py from the Nordic TechDocs Style Guide\n'
          '# (glossary.md and product-names.md). Do not edit by hand.\n')

RED = re.compile(r'<span style="color:\s*red">.*?</span>', re.S)
TAGS = re.compile(r'<[^>]+>')
PAREN = re.compile(r'\([^)]*\)')
LINK = re.compile(r'\[([^\]]*)\]\([^)]*\)')
WORD = re.compile(r"[A-Za-z][A-Za-z0-9]*(?:[-'][A-Za-z0-9]+)*")


def table_cells(text, column):
    """Yield one column of every Markdown table row, header and separator rows excluded."""
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith('|') or re.match(r'^\|[\s:|-]+\|$', line):
            continue
        cells = [c.strip() for c in line.strip('|').split('|')]
        if len(cells) > column:
            yield cells[column]


def terms_from_glossary(path):
    text = open(path, encoding='utf-8').read()
    start = text.find('## List of Terms')
    text = text[start:] if start >= 0 else text
    for cell in table_cells(text, 0):
        if cell.lower().startswith('correct use of term'):
            continue
        yield cell


def terms_from_product_names(path):
    """Yield the first column of the product-name tables, except rows of prohibited forms."""
    text = open(path, encoding='utf-8').read()
    for cell in table_cells(text, 0):
        if not re.search(r'(?i)not allowed|prohibited|incorrect|context|product type', cell):
            yield cell


def words(chunks):
    found = set()
    for chunk in chunks:
        chunk = RED.sub(' ', chunk)
        chunk = LINK.sub(r'\1', chunk)
        chunk = TAGS.sub(' ', chunk)
        chunk = PAREN.sub(' ', chunk)
        # File extensions (.pdf), prefixes (pre-), and URLs are not words.
        chunk = re.sub(r'https?://\S+|\.\w+|\b\w+-(?=\s|$)', ' ', chunk)
        chunk = re.sub(r'`[^`]*`', ' ', chunk)
        chunk = chunk.replace('*', ' ').replace('®', ' ').replace('™', ' ')
        for w in WORD.findall(chunk):
            # Vale's default spelling filters skip hyphenated words.
            if len(w) > 1 and '-' not in w:
                found.add(w)
    return found


# Nordic rules that flag prohibited terms and case variants, such as BLE or NRF52840.
PROHIBITING = ('Glossary', 'GlossaryPreferred', 'Terms', 'Avoid', 'InformalAbbreviations')


def flagged_by(words_, ini):
    """Return the words that Vale flags with the given configuration, one word per line."""
    with tempfile.TemporaryDirectory() as tmp:
        ordered = sorted(words_)
        sample = os.path.join(tmp, 'words.txt')
        with open(sample, 'w') as f:
            f.write('\n\n'.join(ordered) + '\n')
        with open(os.path.join(tmp, '.vale.ini'), 'w') as f:
            f.write(ini.replace('{tmp}', tmp))
        if not os.path.isdir(os.path.join(tmp, 'Check')):
            os.mkdir(os.path.join(tmp, 'Check'))
            with open(os.path.join(tmp, 'Check', 'Spelling.yml'), 'w') as f:
                f.write("extends: spelling\nmessage: '%s'\nlevel: error\n")
        res = subprocess.run(['vale', '--config', os.path.join(tmp, '.vale.ini'), '--output=JSON', sample],
                             capture_output=True, text=True)
        if res.returncode not in (0, 1):
            sys.exit('vale failed: %s' % res.stderr.strip())
        data = json.loads(res.stdout or '{}')
        return {ordered[(a['Line'] - 1) // 2] for alerts in data.values() for a in alerts}


def vocabulary(candidates):
    """Keep the words that Vale's default dictionary does not know and no Nordic rule prohibits."""
    unknown = flagged_by(candidates, 'StylesPath = {tmp}\n[*.txt]\nCheck.Spelling = YES\n')
    rules = ''.join('Nordic.%s = YES\n' % r for r in PROHIBITING)
    prohibited = flagged_by(unknown, 'StylesPath = %s\n[*.txt]\n%s' % (REPO, rules))
    return unknown - prohibited


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--guide', required=True, help='path to the techdocs-style-guide repository')
    ap.add_argument('--check', action='store_true', help='fail if accept.txt is out of date')
    args = ap.parse_args()

    docs = os.path.join(args.guide, 'docs')
    chunks = list(terms_from_glossary(os.path.join(docs, 'glossary.md')))
    chunks += list(terms_from_product_names(os.path.join(docs, 'product-names.md')))
    vocab = sorted(vocabulary(words(chunks)), key=lambda w: (w.lower(), w))
    content = HEADER + ''.join(w + '\n' for w in vocab)

    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if args.check:
        if old != content:
            print('%s is out of date. Run scripts/gen-vocab.py --guide %s' % (os.path.relpath(OUT, REPO), args.guide))
            return 1
        print('%s is up to date (%d words).' % (os.path.relpath(OUT, REPO), len(vocab)))
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(content)
    print('Wrote %d words to %s.' % (len(vocab), os.path.relpath(OUT, REPO)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
